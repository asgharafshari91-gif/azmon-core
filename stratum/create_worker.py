#!/usr/bin/env python3
"""Create a local AZMON mainnet device; never changes the live Supabase project."""
import argparse,getpass,hashlib,json,os,pathlib,secrets,sys,uuid
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--file',required=True);p.add_argument('--address',required=True);a=p.parse_args()
if not a.address.startswith('az1'):p.error('Use an AZMON mainnet az1 address generated by this package. Server also validates its checksum.')
f=pathlib.Path(a.file);f.parent.mkdir(parents=True,exist_ok=True)
rows=json.loads(f.read_text()) if f.exists() else {};worker=str(uuid.uuid4());token=secrets.token_hex(32)
rows[worker]={'address':a.address,'tokenHash':hashlib.sha256(token.encode()).hexdigest(),'enabled':True}
tmp=f.with_name(f.name+'.tmp-'+secrets.token_hex(6));fd=os.open(tmp,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
with os.fdopen(fd,'w') as stream:json.dump(rows,stream,indent=2)
os.replace(tmp,f)
print('AZMON Worker UUID:',worker);print('Device key (shown once):',token)
